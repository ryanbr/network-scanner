#!/usr/bin/env node
/**
 * Extraction parity between the two copies of extractDomainFromRule.
 *
 * `lib/output.js` and `lib/post-processing.js` each define their own
 * extractDomainFromRule, and both feed the SAME decision: take a rule nwss
 * wrote, recover its domain, and drop the rule if it matches ignoreDomains
 * (lib/output.js:521 in handleOutput, cleanupIgnoreDomains in
 * post-processing). When one copy fails to recover a domain it does not throw
 * -- it returns something that matches nothing, so the rule is silently KEPT
 * and the operator sees a domain they asked to ignore.
 *
 * That has now happened twice, once in each copy:
 *
 *   - unbound, in post-processing. REGEX_UNBOUND captured the root dot that
 *     unbound writes, so extraction returned 'example.com.' and neither
 *     equality nor the subdomain suffix held. Fixed in 4.1.1; pinned by
 *     scripts/test-post-processing.js, which also compares the two copies on
 *     four unbound strings.
 *   - dnsmasq and path rules, in output.js. 'local=/' is seven characters and
 *     substring(6) started on the slash, returning '/domain.com'; 'server=/'
 *     is eight with the same off-by-one. Separately, the adblock branch was
 *     guarded on includes('^'), so the ||domain.com/path/ form that
 *     output_regex produces fell through to the plain-domain fallback and
 *     returned the whole rule. Three formats escaping ignoreDomains, silently.
 *
 * WHY THIS FILE rather than more strings in test-post-processing.js: that
 * file's four unbound literals only pin the format that broke. The corpus here
 * is GENERATED by calling formatDomain for every output mode, so it cannot
 * drift from what nwss actually writes -- add an output format and it is
 * covered without touching this file.
 *
 * WHAT IS COMPARED: the recovered domain, across three properties.
 *   1. the two copies agree
 *   2. the recovered value round-trips to the bare host that was formatted
 *   3. the consequence -- buildOutputLines actually drops an ignored domain in
 *      every format, which is the behaviour the two bugs above broke
 *
 * No browser, no network. Runs in well under a second.
 */

const output = require('../lib/output.js');
const pp = require('../lib/post-processing.js');

let failures = 0;
let checks = 0;
const check = (name, ok, detail) => {
  checks++;
  console.log(`  ${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? ' — ' + detail : ''}`);
  if (!ok) failures++;
};

// Every output mode formatDomain can produce. The keys are labels; the values
// are the options object handleOutput passes through.
const FORMATS = {
  adblock:       {},
  adblockScript: { adblockRules: true, resourceType: 'script' },
  plain:         { plain: true },
  'hosts 0.0.0.0':   { localhostIP: '0.0.0.0' },
  'hosts 127.0.0.1': { localhostIP: '127.0.0.1' },
  dnsmasq:       { dnsmasq: true },
  dnsmasqOld:    { dnsmasqOld: true },
  unbound:       { unbound: true },
  privoxy:       { privoxy: true },
  pihole:        { pihole: true }
};

// A plain host, a bare apex, a multi-label host under a two-part public suffix,
// a punycode label, and the host/path/ key that output_regex produces.
const KEYS = [
  'ads.example.com',
  'example.com',
  'a.b.c.example.co.uk',
  'xn--p1ai.example.com',
  'ads.example.com/path/'
];
const hostOf = key => (key.includes('/') ? key.slice(0, key.indexOf('/')) : key);

console.log('\n--- 1. the two copies agree on every rule nwss writes');
let pairs = 0;
for (const key of KEYS) {
  for (const [label, opts] of Object.entries(FORMATS)) {
    const rule = output.formatDomain(key, opts);
    if (!rule) continue;
    pairs++;
    const a = output.extractDomainFromRule(rule);
    const b = pp.extractDomainFromRule(rule);
    if (String(a) !== String(b)) {
      check(`${label} / ${key}`, false, `output=${JSON.stringify(a)} post-processing=${JSON.stringify(b)}`);
    }
  }
}
check(`all ${pairs} generated rules agree across both copies`, failures === 0,
  `${pairs} rules, ${FORMATS ? Object.keys(FORMATS).length : 0} formats x ${KEYS.length} keys`);

console.log('\n--- 2. the recovered domain round-trips to the host that was formatted');
for (const key of KEYS) {
  const want = hostOf(key);
  for (const [label, opts] of Object.entries(FORMATS)) {
    const rule = output.formatDomain(key, opts);
    if (!rule) continue;
    const got = output.extractDomainFromRule(rule);
    if (String(got) !== want) {
      check(`${label} / ${key}`, false, `got ${JSON.stringify(got)}, want ${JSON.stringify(want)}`);
    }
  }
}
check('every format round-trips through output.js', failures === 0);

console.log('\n--- 3. the consequence: ignoreDomains drops the rule in every format');
// This is what the dnsmasq and path-rule bugs actually broke. buildOutputLines
// is the real consumer: it extracts the domain and filters on ignoreDomains,
// so a format whose domain cannot be recovered keeps the rule and says nothing.
for (const [label, opts] of Object.entries(FORMATS)) {
  const rule = output.formatDomain('ads.example.com', opts);
  if (!rule) continue;
  const keep = output.formatDomain('keep.example.net', opts);
  // buildOutputLines returns { outputLines, filteredOutCount, ... }; the count
  // is the filter's own tally, so it catches a rule dropped for the wrong
  // reason as well as one wrongly kept.
  const res = output.buildOutputLines(
    [{ url: 'https://scanned.example/', success: true, rules: [rule, keep] }],
    { ignoreDomains: ['ads.example.com'], silentMode: true }
  );
  const text = (res.outputLines || []).join('\n');
  check(`${label}: an ignored domain is filtered out`,
    !text.includes(rule) && res.filteredOutCount === 1,
    `${JSON.stringify(rule)} filteredOutCount=${res.filteredOutCount}`);
  check(`${label}: a non-ignored domain survives`, text.includes(keep), JSON.stringify(keep));
}

console.log(`\n${failures === 0 ? '✅' : '❌'} ${checks - failures} passed, ${failures} failed\n`);
process.exit(failures === 0 ? 0 : 1);
